class RealTree(GateCase):
    def test_real_tree_passes(self):
        result = self.run_gate(REPO_ROOT)
        self.assertPasses(result)

    def test_real_tree_vendors_upstream_licence_and_notice(self):
        # The vendored licence decision: the pack LICENSE and NOTICE are vendored byte for byte under .aiqt/.
        # The gate reads its file set from the pin, so this test also fails when either file is dropped
        # from the pin rather than altered.
        import tomllib
        pin = tomllib.loads((REPO_ROOT / ".aiqt/pin.toml").read_text(encoding="utf-8"))
        manifest = tomllib.loads((REPO_ROOT / pin["integrity"]["manifest"]).read_text(encoding="utf-8"))
        sources = {e["path"]: (e["bytes"], e["sha256"]) for e in manifest["sources"]}
        relocated = {e["path"]: e["upstream"] for e in pin["vendor"].get("relocated", [])}
        listed = {e["path"]: (e["bytes"], e["sha256"]) for e in pin["vendor"]["files"]}
        for local, upstream in sorted(RELOCATED.items()):
            with self.subTest(path=local):
                self.assertEqual(relocated.get(local), upstream)
                self.assertIn(local, pin["vendored"]["paths"])
                path = REPO_ROOT / local
                self.assertTrue(path.is_file() and not path.is_symlink(), local)
                data = path.read_bytes()
                self.assertEqual((len(data), sha(data)), sources[upstream])
                self.assertEqual(listed.get(local), sources[upstream])
                if upstream == "LICENSE":
                    self.assertEqual(sha(data), pin["vendor"]["license-sha256"])


