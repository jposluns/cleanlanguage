#!/usr/bin/env python3
"""Tests for tools/check-aiqt-vendor.py.

Every check of the vendor integrity gate is driven red by a fixture tree that breaks exactly what the
check guards, and green by an intact fixture. Each fixture is a throwaway git repository built under
TMPDIR, carrying a small rule corpus, two active rule trees, a three-file hooks plugin, a generated-style
manifest, a release root, and a pin with the `[vendor]` block the gate reads. The check 7 fixtures add a
second repository standing in for the pack checkout. The relocation fixtures add a licence and a notice
vendored under .aiqt/ and mapped to the pack root by `[[vendor.relocated]]`. Failure assertions match the
gate marker
`FAIL check N:` for the check under test, so a test goes red when that check is removed even if another
check still fails. The RealTree class runs the gate against this checkout and expects green; it needs
the pin to carry the `[vendor]` block and the `[active-rules]` keys the gate reads, and checks that this
checkout vendors the upstream LICENSE and NOTICE unaltered (the vendored licence decision), so dropping either
file from the pin, as well as altering it, turns the suite red.

Runs offline with the standard library and git; every Python launch is isolated (-I).
"""

import hashlib
import json
import os
import shutil
import stat
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

HERE = Path(__file__).resolve().parent
GATE = HERE / "check-aiqt-vendor.py"
REPO_ROOT = HERE.parent
PY = sys.executable
HEADER = "# generated by tools/gen_manifest.py; do not hand-edit (VER-CORE 4.1)"
MANIFEST = ".aiqt/manifest.toml"
ROOT_TXT = ".aiqt/release/root.txt"
FAKE_COMMIT = "a" * 40
FAKE_TREE = "b" * 64
FAKE_ROOT = "sha256:" + "c" * 64
LICENSE = b"Apache License\nVersion 2.0, January 2004\nfixture text\n"
NOTICE = b"AIQT Guardrails\nfixture notice text\n"
RELOCATED = {".aiqt/LICENSE": "LICENSE", ".aiqt/NOTICE": "NOTICE"}
VENDORED = [".aiqt/core/rules", ".aiqt/core/applies.toml", ".aiqt/core/order.toml", MANIFEST, ROOT_TXT,
            "plugin/aiqt-guardrails-hooks", ".claude/rules/aiqt", ".claude/rules/security"]
PLUGIN = ["plugin/aiqt-guardrails-hooks/.claude-plugin/plugin.json",
          "plugin/aiqt-guardrails-hooks/hooks/hooks.json",
          "plugin/aiqt-guardrails-hooks/hooks/scripts/aiqt_hooks.py"]
RENDERS = {".claude/rules/aiqt/10-ALPHA.md": "alpha", ".claude/rules/aiqt/10-BETA.md": "beta",
           ".claude/rules/security/SEC-GAMMA.md": "gamma"}
EXCLUDED_RENDER = ".claude/rules/aiqt/10-DELTA.md"


def sha(data):
    return hashlib.sha256(data).hexdigest()


def rule(cid):
    return "---\ncorpus-id: {}\norigin: pack\n---\n\n# Rule {}\n\nBody of {}.\n".format(cid, cid, cid).encode()


def git_env():
    env = {k: v for k, v in os.environ.items() if not k.startswith("GIT_")}
    env["GIT_CONFIG_NOSYSTEM"] = "1"
    env["GIT_CONFIG_GLOBAL"] = os.devnull
    return env


def git(repo, *args):
    return subprocess.run(["git", "-C", str(repo), "-c", "user.name=fixture", "-c",
                           "user.email=fixture@example.invalid", "-c", "commit.gpgsign=false"] + list(args),
                          capture_output=True, check=True, env=git_env(), timeout=60)


def toml_value(value):
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, str):
        return json.dumps(value)
    if isinstance(value, list):
        return "[" + ", ".join(toml_value(v) for v in value) + "]"
    raise TypeError(value)


def dump_pin(pin):
    lines = []
    for table, body in pin.items():
        arrays = {k: v for k, v in body.items() if isinstance(v, list) and v and isinstance(v[0], dict)}
        lines.append("[{}]".format(table))
        for key, value in body.items():
            if key not in arrays:
                lines.append("{} = {}".format(key, toml_value(value)))
        lines.append("")
        for key, rows in arrays.items():
            for row in rows:
                lines.append("[[{}.{}]]".format(table, key))
                for k, v in row.items():
                    lines.append("{} = {}".format(k, toml_value(v)))
                lines.append("")
    return "\n".join(lines) + "\n"


def dump_manifest(header, tree, sources, artifacts):
    lines = [header, "format-version = 1", "release-version = \"9.9.9\"", "tree-sha256 = " + json.dumps(tree), ""]
    for path in sorted(sources):
        size, digest = sources[path]
        lines += ["[[sources]]", "path = " + json.dumps(path), "bytes = {}".format(size),
                  "sha256 = " + json.dumps(digest), ""]
    for path in sorted(artifacts):
        lines += ["[[artifacts]]", "artifact-id = " + json.dumps("rules:" + path), "path = " + json.dumps(path),
                  "kind = \"file\"", "sha256 = " + json.dumps(artifacts[path]), ""]
    return "\n".join(lines)


def base_spec():
    files = {}
    for cid in ("alpha", "beta", "gamma", "delta"):
        files[".aiqt/core/rules/{}.md".format(cid)] = rule(cid)
    files[".aiqt/core/applies.toml"] = b"[applies]\nalpha = \"always\"\n"
    files[".aiqt/core/order.toml"] = b"order = [\"alpha\", \"beta\", \"gamma\", \"delta\"]\n"
    files[PLUGIN[0]] = b"{\"name\": \"aiqt-guardrails-hooks\", \"version\": \"0.4.0\"}\n"
    files[PLUGIN[1]] = b"{\"hooks\": {}}\n"
    files[PLUGIN[2]] = b"import sys\nsys.exit(0)\n"
    for path, cid in RENDERS.items():
        files[path] = rule(cid)
    files[ROOT_TXT] = (FAKE_ROOT + "\n").encode()
    files["README.md"] = b"Not vendored.\n"
    pin = {
        "source": {"name": "aiqt-guardrails", "license": "Apache-2.0", "source-commit": FAKE_COMMIT},
        "version": {"pack": "9.9.9"},
        "integrity": {"tree-sha256": FAKE_TREE, "root": FAKE_ROOT, "manifest": MANIFEST},
        "vendored": {"paths": list(VENDORED)},
        "active-rules": {"active": 3, "excluded": 1, "excluded-ids": ["delta"], "corpus": ".aiqt/core/rules",
                         "trees": [".claude/rules/aiqt", ".claude/rules/security"]},
        "vendor": {"source-commit": FAKE_COMMIT, "source-date": "2026-10-30T03:03:04-04:00",
                   "license-sha256": sha(LICENSE), "verified": "fixture",
                   "whole": [".aiqt/core/rules", "plugin/aiqt-guardrails-hooks"], "files": "AUTO"},
    }
    return {"files": files, "pin": pin, "header": HEADER, "tree": FAKE_TREE, "edit": None, "disk": None,
            "upstream": False, "upstream_edit": None, "extra_artifacts": {EXCLUDED_RENDER: sha(rule("delta"))},
            "relocated": {}}


def _write(root, rel, data):
    path = root / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data)


def _vendored(path, vendored):
    return any(path == v or path.startswith(v + "/") for v in vendored)


def build(base, spec):
    """Build the fixture; return (consumer root, upstream root or None)."""
    root = base / "repo"
    root.mkdir()
    files = spec["files"]
    relocated = spec["relocated"]
    vendored = VENDORED + sorted(relocated)
    sources = {relocated.get(p, p): (len(d), sha(d)) for p, d in files.items()
               if _vendored(p, vendored) and p not in (MANIFEST, ROOT_TXT)}
    artifacts = {p: sha(d) for p, d in files.items()
                 if p.startswith(".claude/rules/aiqt/") or p.startswith(".claude/rules/security/")}
    artifacts.update(spec["extra_artifacts"])
    pin = json.loads(json.dumps(spec["pin"]))
    if pin.get("vendor", {}).get("files") == "AUTO":
        pin["vendor"]["files"] = [{"path": p, "bytes": len(files[p]), "sha256": sha(files[p])}
                                  for p in PLUGIN + sorted(relocated) if p in files]
    if relocated and isinstance(pin.get("vendor"), dict) and "relocated" not in pin["vendor"]:
        pin["vendor"]["relocated"] = [{"path": p, "upstream": u} for p, u in sorted(relocated.items())]
    if spec["edit"] is not None:
        spec["edit"](pin, sources, artifacts)
    manifest = dump_manifest(spec["header"], spec["tree"], sources, artifacts).encode()
    for rel, data in files.items():
        _write(root, rel, data)
    _write(root, MANIFEST, manifest)
    upstream = None
    if spec["upstream"]:
        upstream = base / "pack"
        upstream.mkdir()
        up_files = {relocated.get(p, p): d for p, d in files.items() if _vendored(p, vendored)}
        up_files[MANIFEST] = manifest
        up_files["LICENSE"] = LICENSE
        if spec["upstream_edit"] is not None:
            spec["upstream_edit"](up_files)
        for rel, data in up_files.items():
            _write(upstream, rel, data)
        git(upstream, "init", "-q")
        git(upstream, "add", "-A")
        git(upstream, "commit", "-q", "-m", "pack fixture")
        commit = git(upstream, "rev-parse", "HEAD").stdout.decode("ascii").strip()
        if pin["source"].get("source-commit") == FAKE_COMMIT:
            pin["source"]["source-commit"] = commit
        if pin.get("vendor", {}).get("source-commit") == FAKE_COMMIT:
            pin["vendor"]["source-commit"] = commit
    _write(root, ".aiqt/pin.toml", dump_pin(pin).encode())
    git(root, "init", "-q")
    git(root, "add", "-A")
    if spec["disk"] is not None:
        spec["disk"](root)
    return root, upstream


class GateCase(unittest.TestCase):
    def setUp(self):
        self.base = Path(tempfile.mkdtemp(prefix="aiqt-vendor-test-"))
        self.addCleanup(self._cleanup)

    def _cleanup(self):
        for dirpath, dirnames, filenames in os.walk(self.base):
            for name in dirnames:
                p = os.path.join(dirpath, name)
                if not os.path.islink(p):
                    os.chmod(p, 0o700)
            for name in filenames:
                p = os.path.join(dirpath, name)
                if not os.path.islink(p) and stat.S_ISREG(os.lstat(p).st_mode):
                    os.chmod(p, 0o600)
        shutil.rmtree(self.base, ignore_errors=True)

    def run_gate(self, root, *extra, launcher=None):
        cmd = launcher if launcher is not None else [PY, "-I", str(GATE)]
        return subprocess.run(cmd + ["--root", str(root)] + list(extra), capture_output=True, text=True,
                              timeout=60, env=git_env())

    def spec_run(self, mutate=None, upstream=False):
        spec = base_spec()
        spec["upstream"] = upstream
        if mutate is not None:
            mutate(spec)
        root, up = build(self.base, spec)
        extra = ["--upstream", str(up)] if upstream else []
        return self.run_gate(root, *extra)

    def assertPasses(self, result):
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertIn("check-aiqt-vendor: OK:", result.stdout)

    def assertCheckFails(self, result, check):
        self.assertEqual(result.returncode, 1, result.stdout + result.stderr)
        self.assertIn("FAIL check {}:".format(check), result.stderr)

    def assertCannotEvaluate(self, result, fragment):
        self.assertEqual(result.returncode, 1, result.stdout + result.stderr)
        self.assertIn("FAIL: cannot evaluate", result.stderr)
        self.assertIn(fragment, result.stderr)


def edit_pin(fn):
    def mutate(spec):
        old = spec["edit"]

        def edit(pin, sources, artifacts):
            if old is not None:
                old(pin, sources, artifacts)
            fn(pin)
        spec["edit"] = edit
    return mutate


def edit_manifest(fn):
    def mutate(spec):
        spec["edit"] = lambda pin, sources, artifacts: fn(sources, artifacts)
    return mutate


def on_disk(fn):
    def mutate(spec):
        spec["disk"] = fn
    return mutate


