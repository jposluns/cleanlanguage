#!/usr/bin/env python3
"""Check the install page keeps its family sections static, visible, and complete.

``site/install/index.html`` shows five AI-family setup sections (Claude, ChatGPT,
Gemini, Copilot, and other AI systems). It is generated by
``tools/build-site.py`` on the shared template (baseline). The template's
selector, ``site/assets/baseline/select.js``, lets a reader narrow the page to
one family (template specification, section 7.12). The point is that this is an
enhancement. With JavaScript blocked, failed, or switched off, the selector
never runs and all five sections show.

This is a TRIPWIRE for the common regressions in the STATIC MARKUP. It is
deliberately NOT a CSS engine or a browser.

What it verifies
----------------

1. Each family id exists exactly once on a ``<section id=X data-family-section=X>``
   with an ``<h2>`` that has visible text, carries none of ``hidden``, ``inert``,
   ``aria-hidden="true"`` (any case) or the ``visually-hidden`` class on itself,
   and no other element carries ``data-family-section``.
2. Exactly 1 ``ul.picker[data-picker]`` holds exactly 1
   ``<a data-family-link=X href="#X">`` per family, none with ``aria-current``;
   no ``data-family-link`` sits outside it; exactly 1 ``data-picker-reset``
   button exists and is ``hidden``; exactly 1 ``data-picker-status`` region exists.
3. The ids ``pick``, ``get``, ``test``, ``how-to-use``, ``spelling`` and
   ``assurance`` exist (existing deep links, such as ``/install/#pick``), and no
   id is duplicated.
4. No inline code and no refused markup, as checks 1 to 10 of
   ``tools/check-inline-code.py`` define them for an HTML page, with that
   gate's own code: among them, no ``<script>`` without ``src`` other than a
   structured-data block, no ``on*`` attribute, no ``javascript:`` URL, no
   ``<style>`` element or ``style`` attribute, no script from another origin,
   and none of the elements that the parser reads differently from a browser;
   and, by its check 7, exactly 1 element with ``data-scheme-toggle``, the
   light and dark switch of template specification 7.33, in its place.
5. Versioned asset tokens: ``fonts.css``, ``palettes.css``, ``baseline.css``,
   ``copy.js`` and ``select.js`` load from ``/assets/baseline/`` with
   ``?v=X.Y.Z``, the scripts with ``defer``; an optional ``site.css`` loads with
   ``?v=`` and 12 hexadecimal characters. ``scheme.js`` loads exactly once, as
   exactly ``<script data-cfasync="false" src="/assets/baseline/scheme.js?v=X.Y.Z"></script>``,
   with no ``defer`` or ``async``, before the first stylesheet, and it and every
   stylesheet start inside ``<head>``, read as parsed elements: ``html > head``,
   the first head or body the page opens (template specification 7.33, baseline
   1.6.0), before the head ends where HTML5 ends it: at the first text other
   than whitespace, start tag other than those HTML5 allows in a head
   (``HEAD_TAGS``), or ``</body>``, ``</html>`` or ``</br>``. A self-closing tag
   leaves an element that is neither void nor in ``<svg>`` open, as in a
   browser. The reading fails closed where it does not model HTML5: such a
   start tag inside a ``<template>`` or ``<noscript>`` in the head ends the
   head, and a self-closing tag in ``<math>`` leaves its element open. Every
   other ``<script>`` the page loads is 1 of the baseline's
   other scripts that this site copies (``BASELINE_SCRIPTS``: ``copy.js``,
   ``select.js``, ``search.js``, ``rail.js``) from ``/assets/baseline/``, with
   the same token and ``defer``, as exactly
   ``<script src="/assets/baseline/NAME?v=X.Y.Z" defer></script>``; the
   baseline's 6th script, ``matrix.js``, is left out, by the owner's
   decision. Each load is
   read as the parsed element, so a tag inside a comment loads nothing, and a
   ``<script>`` or stylesheet written in another spelling (letter case, a
   character reference, attribute order or spacing) is still counted. Any tag
   that carries an attribute twice fails: a browser reads the first value, and
   this gate's reading would take the last.
6. ``site/_headers``, read with the parser of ``tools/check-headers.py``
   (header names compared without regard to case, comments ignored), has a
   ``/*`` rule that sets ``Content-Security-Policy`` exactly once, to exactly
   the shared policy, ``SHARED_CSP`` below (template specification, baseline
   1.6.0, section 9, unchanged), and does not detach it. No rule sets or detaches
   ``X-Content-Security-Policy``, and no rule other than ``/*`` and ``/draft/*``
   sets, or other than ``/draft/*`` detaches, ``Content-Security-Policy``; a
   ``/draft/*`` rule appears only while a new
   version is staged, and ``tools/check-headers.py`` check 5 holds it to its
   exact lines. The policy allows ``'unsafe-inline'``, so a browser does not
   block inline code on these pages. The site's own pages must not use it
   (template specification, section 5), and check 4 and
   ``tools/check-inline-code.py`` enforce that rule.

What it does NOT verify (the reviewer's and cross-family QA's job)
-----------------------------------------------------------------

It does not run ``select.js`` or apply any stylesheet. It does NOT detect a
stylesheet rule that hides a family section, a hiding ANCESTOR (a wrapping
``hidden`` div, a closed ``<details>``), a custom CLASS that hides, clips, zeroes
opacity or positions off-screen, a DESCENDANT wipe, or hiding by id. Those are
visible regressions a browser check, a reviewer, or the tri-family QA catches.
An exotic heading character may still slip through the visible-text check. The
inline-code checks, and the load reading of check 5, share the residual that
``tools/check-inline-code.py`` states: ``html.parser`` is not a browser's parser.

Exit codes:
  0  the markup is static and complete, and the header discipline holds
  1  a family section, picker link, id, reset, asset token, or header discipline regressed
  3  a file could not be read, or a gate it reuses is missing
"""

from __future__ import annotations

import functools
import importlib.util
import re
import sys
from collections import Counter
from html.parser import HTMLParser
from pathlib import Path
from urllib.parse import unquote

REPO_ROOT = Path(__file__).resolve().parent.parent
PAGE = REPO_ROOT / "site" / "install" / "index.html"
HEADERS = REPO_ROOT / "site" / "_headers"
WHERE = "site/install/index.html"

FAMILIES = ["claude", "chatgpt", "gemini", "copilot", "other-ai"]
TEMPLATE_IDS = ["pick", "get", "test", "how-to-use", "spelling", "assurance"]
BASELINE_SCRIPTS = ("copy.js", "select.js", "search.js", "rail.js")
# scheme.js loads in exactly this form, with no defer, before the stylesheets (specification 7.33).
SCHEME_TAG = re.compile(r'<script data-cfasync="false" src="/assets/baseline/scheme\.js\?v=[0-9]+\.[0-9]+\.[0-9]+"></script>')
# Every other script loads in exactly this form.
DEFERRED_TAG = re.compile(r'<script src="/assets/baseline/([a-z]+\.js)\?v=[0-9]+\.[0-9]+\.[0-9]+" defer></script>')
SITE_SHEET = re.compile(r'<link rel="stylesheet" href="/assets/site\.css\?v=[0-9a-f]{12}">')
DRAFT_PATTERN = "/draft/*"
# The shared policy (template specification, baseline 1.6.0, section 9, unchanged), on every page since promotion.
SHARED_CSP = (
    "default-src 'none'; script-src 'self' 'unsafe-inline' https://ajax.cloudflare.com "
    "https://static.cloudflareinsights.com; connect-src 'self' https://cloudflareinsights.com; "
    "style-src 'self'; font-src 'self'; img-src 'self'; base-uri 'none'; form-action 'none'; "
    "frame-ancestors 'none'"
)
BASELINE_ASSET = r'/assets/baseline/{name}\?v=[0-9]+\.[0-9]+\.[0-9]+"'
VOID = {"meta", "link", "img", "br", "hr", "input", "source", "wbr", "col"}
# The start tags HTML5 allows in a head; any other start tag ends it, as text other than whitespace does.
HEAD_TAGS = {"base", "basefont", "bgsound", "link", "meta", "noframes", "noscript", "script", "style", "template", "title"}
# Invisible characters a heading might be reduced to: zero-width spaces/joiner/BOM,
# no-break and soft-hyphen, word joiner, and the bidi marks.
ZERO_WIDTH = "​‌‍﻿ ⁠‍‌­"

INLINE_RULE = (
    "the site's own pages must not use inline code (template specification, section 5), and this gate "
    "and tools/check-inline-code.py enforce that rule"
)


def die(message: str) -> None:
    print(f"check-install-page: {message}", file=sys.stderr)
    raise SystemExit(3)


@functools.cache
def load_tool(name: str):
    """Load a sibling gate as a module, so this gate applies exactly its logic."""
    path = Path(__file__).resolve().parent / name
    if not path.is_file():
        die(f"tools/{name} does not exist")
    spec = importlib.util.spec_from_file_location(name.removesuffix(".py").replace("-", "_"), path)
    if spec is None or spec.loader is None:
        die(f"tools/{name} could not be loaded")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def inline_code(where: str, text: str) -> list[str]:
    """Check 4: each piece of inline code, read with tools/check-inline-code.py."""
    return [f"{where} {problem}; {INLINE_RULE}." for problem in load_tool("check-inline-code.py").inline_code_problems(text)]


def is_hiding_element(attrs: dict[str, str]) -> bool:
    classes = attrs.get("class", "").split()
    return (
        "hidden" in attrs
        or "inert" in attrs
        or attrs.get("aria-hidden", "").lower() == "true"
        or "visually-hidden" in classes
    )


def has_visible_text(data: str) -> bool:
    return bool(data.translate({ord(c): None for c in ZERO_WIDTH}).strip())


class TemplateParser(HTMLParser):
    """Collects the selector markup of the template install page (specification 7.12)."""

    def __init__(self) -> None:
        super().__init__()
        self.stack: list[dict] = []
        self.family_count = {f: 0 for f in FAMILIES}
        self.family_has_h2 = {f: False for f in FAMILIES}
        self.family_hidden_self: list[str] = []
        self.other_family_carriers: list[str] = []
        self.id_counts: Counter = Counter()
        self.pickers = 0
        self.links: list[tuple[str, str, bool, bool]] = []
        self.resets: list[bool] = []
        self.statuses = 0
        self._h2_family: str | None = None

    def handle_starttag(self, tag: str, attrs_list) -> None:
        attrs = {k.lower(): (v if v is not None else "") for k, v in attrs_list}
        if "id" in attrs:
            self.id_counts[attrs["id"]] += 1
        fam_here = None
        if "data-family-section" in attrs:
            fam = attrs["data-family-section"]
            if tag == "section" and attrs.get("id") == fam and fam in FAMILIES:
                self.family_count[fam] += 1
                fam_here = fam
                if is_hiding_element(attrs):
                    self.family_hidden_self.append(fam)
            else:
                self.other_family_carriers.append(f"<{tag} data-family-section={fam!r}>")
        if tag == "ul" and "data-picker" in attrs and "picker" in attrs.get("class", "").split():
            self.pickers += 1
        if tag == "a" and "data-family-link" in attrs:
            in_picker = any(frame["picker"] for frame in self.stack)
            self.links.append((attrs["data-family-link"], attrs.get("href", ""), in_picker, "aria-current" in attrs))
        if tag == "button" and "data-picker-reset" in attrs:
            self.resets.append("hidden" in attrs)
        if "data-picker-status" in attrs:
            self.statuses += 1
        if tag == "h2":
            self._h2_family = next((f["family"] for f in reversed(self.stack) if f["family"]), None)
        if tag not in VOID:
            picker = tag == "ul" and "data-picker" in attrs
            self.stack.append({"tag": tag, "family": fam_here, "picker": picker})

    def handle_endtag(self, tag: str) -> None:
        if tag == "h2":
            self._h2_family = None
        for i in range(len(self.stack) - 1, -1, -1):
            if self.stack[i]["tag"] == tag:
                del self.stack[i:]
                break

    def handle_data(self, data: str) -> None:
        if self._h2_family and has_visible_text(data):
            self.family_has_h2[self._h2_family] = True


class LoadScan(HTMLParser):
    """Check 5: where each <script> and stylesheet <link> element starts, which of them start outside the
    page's head, and each tag that repeats an attribute."""

    def __init__(self, text: str) -> None:
        super().__init__()
        self.lines = [0] + [match.end() for match in re.finditer("\n", text)]
        self.scripts: list[tuple[int, dict[str, str], str]] = []
        self.sheets: list[tuple[int, dict[str, str], str]] = []
        self.repeats: list[str] = []
        # The open elements, and the head or body elements opened so far: the page's head is html > head,
        # the first of them, until the head ends where HTML5 ends it.
        self.stack: list[str] = []
        self.heads = 0
        self.head_ended = False
        self.outside_head: set[int] = set()

    def handle_starttag(self, tag: str, attrs_list) -> None:
        attrs = {k.lower(): (v if v is not None else "") for k, v in attrs_list}
        line, column = self.getpos()
        element = (self.lines[line - 1] + column, attrs, self.get_starttag_text() or "")
        if len(attrs) != len(attrs_list):
            # A browser reads the first of 2 attributes with the same name, and these dicts the last.
            self.repeats.append(element[2])
        if tag in ("head", "body"):
            self.heads += 1
        if tag not in HEAD_TAGS and tag not in ("html", "head"):
            self.head_ended = True
        if tag in ("script", "link") and (self.stack != ["html", "head"] or self.heads != 1 or self.head_ended):
            self.outside_head.add(element[0])
        if tag not in VOID:
            self.stack.append(tag)
        if tag == "script":
            self.scripts.append(element)
        elif tag == "link" and "stylesheet" in attrs.get("rel", "").lower().split():
            self.sheets.append(element)

    def handle_startendtag(self, tag: str, attrs_list) -> None:
        # A browser honours the slash only in <svg> (foreign content); any other element that is not void stays open.
        foreign = tag == "svg" or "svg" in self.stack
        self.handle_starttag(tag, attrs_list)
        if tag not in VOID and foreign:
            self.handle_endtag(tag)

    def handle_endtag(self, tag: str) -> None:
        if tag in ("body", "html", "br"):
            # HTML5 ends the head at each of these end tags (</br> reads as <br>).
            self.head_ended = True
        for i in range(len(self.stack) - 1, -1, -1):
            if self.stack[i] == tag:
                del self.stack[i:]
                break

    def handle_data(self, data: str) -> None:
        if data.strip(" \t\n\f\r") and self.stack in ([], ["html"], ["html", "head"]):
            # Text other than whitespace in or before the head ends it (HTML5).
            self.head_ended = True


def check_template_page(text: str) -> list[str]:
    """Checks 1 to 5."""
    parser = TemplateParser()
    parser.feed(text)
    problems: list[str] = []
    where = WHERE
    for fam in FAMILIES:
        n = parser.family_count[fam]
        if n != 1:
            problems.append(f"{where}: the {fam} family section appears {n} times; it must appear exactly once.")
        elif not parser.family_has_h2[fam]:
            problems.append(f"{where}: the {fam} family section has no <h2> with visible text.")
    for fam in parser.family_hidden_self:
        problems.append(f"{where}: the {fam} family section is hidden in the static markup.")
    for extra in parser.other_family_carriers:
        problems.append(f"{where}: data-family-section appears on an unexpected element {extra}.")
    if parser.pickers != 1:
        problems.append(f'{where}: {parser.pickers} <ul class="picker" data-picker> lists; exactly 1 is required.')
    for fam in FAMILIES:
        mine = [link for link in parser.links if link[0] == fam]
        if len(mine) != 1:
            problems.append(f"{where}: the {fam} picker link appears {len(mine)} times; it must appear exactly once.")
            continue
        _, href, in_picker, current = mine[0]
        if href != f"#{fam}":
            problems.append(f'{where}: the {fam} picker link points at {href!r}, not "#{fam}".')
        if not in_picker:
            problems.append(f"{where}: the {fam} picker link is outside the data-picker list, so select.js would not find it.")
        if current:
            problems.append(f"{where}: the {fam} picker link carries aria-current in the static markup; only select.js may set it.")
    for fam, *_ in parser.links:
        if fam not in FAMILIES:
            problems.append(f"{where}: a picker link names an unknown family {fam!r}.")
    if len(parser.resets) != 1:
        problems.append(f"{where}: {len(parser.resets)} data-picker-reset buttons; exactly 1 is required.")
    elif not parser.resets[0]:
        problems.append(f"{where}: the data-picker-reset button is not hidden in the static markup.")
    if parser.statuses != 1:
        problems.append(f"{where}: {parser.statuses} data-picker-status regions; exactly 1 is required.")
    for dup_id, count in sorted(parser.id_counts.items()):
        if count > 1:
            problems.append(f'{where}: the id "{dup_id}" appears {count} times.')
    for gid in TEMPLATE_IDS:
        if parser.id_counts.get(gid, 0) == 0:
            problems.append(f'{where}: the id "{gid}" is missing; existing deep links use it.')
    problems += inline_code(where, text)
    loads = LoadScan(text)
    loads.feed(text)
    loads.close()
    for tag in loads.repeats:
        problems.append(f"{where}: {tag} carries an attribute twice; a browser reads the first, this gate the last.")
    for name in ("fonts.css", "palettes.css", "baseline.css"):
        sheet = re.compile(r'<link rel="stylesheet" href="' + BASELINE_ASSET.format(name=re.escape(name)))
        if not any(sheet.match(text, at) for at, _, _ in loads.sheets):
            problems.append(f"{where}: {name} is not loaded from /assets/baseline/ with a ?v=X.Y.Z token.")
    scheme_tags = [at for at, _, _ in loads.scripts if SCHEME_TAG.match(text, at)]
    deferred = []
    for at, attrs, tag in loads.scripts:
        if "src" not in attrs or at in scheme_tags:
            continue
        name = DEFERRED_TAG.match(text, at)
        if name is None or name.group(1) not in BASELINE_SCRIPTS:
            problems.append(f"{where}: {tag} is not 1 of the baseline scripts this site copies with a ?v=X.Y.Z token and defer.")
        else:
            deferred.append(name.group(1))
    for name in ("copy.js", "select.js"):
        if name not in deferred:
            problems.append(f"{where}: {name} is not loaded from /assets/baseline/ with a ?v=X.Y.Z token and defer.")
    first_sheet = min((at for at, _, _ in loads.sheets), default=-1)
    if len(scheme_tags) != 1:
        problems.append(
            f'{where}: scheme.js loads {len(scheme_tags)} times as <script data-cfasync="false" '
            'src="/assets/baseline/scheme.js?v=X.Y.Z"></script>; exactly 1 is required.'
        )
    elif first_sheet == -1 or scheme_tags[0] > first_sheet:
        problems.append(f"{where}: scheme.js does not load before the first stylesheet.")
    elif scheme_tags[0] in loads.outside_head or any(at in loads.outside_head for at, _, _ in loads.sheets):
        problems.append(f"{where}: scheme.js or a stylesheet does not load inside <head>.")
    site_sheets = [at for at, attrs, _ in loads.sheets if "site.css" in unquote(attrs.get("href", ""))]
    if ("/assets/site.css" in text or site_sheets) and not (site_sheets and all(SITE_SHEET.match(text, at) for at in site_sheets)):
        problems.append(f"{where}: site.css is not loaded with a ?v= content token.")
    return problems


def check_headers(headers: str) -> list[str]:
    """Check 6: the site-wide policy, read with the parser of tools/check-headers.py."""
    problems: list[str] = []
    entries = load_tool("check-headers.py").parse(headers)
    site_csp = [
        (number, kind, value) for number, pattern, kind, name, value in entries
        if pattern == "/*" and name.lower() == "content-security-policy"
    ]
    if len(site_csp) != 1 or site_csp[0][1] != "set":
        problems.append(
            f"the /* rule of site/_headers sets or detaches Content-Security-Policy {len(site_csp)} times "
            "(lines " + (", ".join(str(entry[0]) for entry in site_csp) or "none") + "); "
            "it must set it exactly once and detach it nowhere."
        )
    elif site_csp[0][2] != SHARED_CSP:
        problems.append(
            f"the site-wide Content-Security-Policy (site/_headers line {site_csp[0][0]}) is not exactly "
            f"the shared policy: {site_csp[0][2]!r}"
        )
    for number, pattern, kind, name, _ in entries:
        if name.lower() == "x-content-security-policy":
            problems.append(
                f"site/_headers line {number} names X-Content-Security-Policy under {pattern}; "
                "only Content-Security-Policy carries the policy."
            )
        elif name.lower() == "content-security-policy" and kind == "detach" and pattern not in ("/*", DRAFT_PATTERN):
            problems.append(
                f"site/_headers line {number} detaches Content-Security-Policy under {pattern}; only "
                f"{DRAFT_PATTERN} may detach it, because it sets the same policy again."
            )
        elif name.lower() == "content-security-policy" and kind == "set" and pattern not in ("/*", DRAFT_PATTERN):
            problems.append(
                f"site/_headers line {number} sets a Content-Security-Policy for {pattern}; only /* and "
                f"{DRAFT_PATTERN} may set one."
            )
    return problems


def main() -> int:
    for path in (PAGE, HEADERS):
        if not path.is_file():
            die(f"{path.relative_to(REPO_ROOT)} does not exist")
    try:
        page_text = PAGE.read_text(encoding="utf-8")
        headers = HEADERS.read_text(encoding="utf-8")
    except (OSError, UnicodeError) as error:
        die(f"a file could not be read: {error}")

    problems = check_template_page(page_text) + check_headers(headers)

    if problems:
        print("Install page problems found:")
        for problem in problems:
            print(f"  - {problem}")
        return 1

    print(
        "The install page carries all five family sections statically and visibly, ids are "
        "unique, the picker and its single hidden reset are present with no pre-set state, "
        "it carries no inline code and loads only the baseline's versioned assets, and the "
        "/* rule of site/_headers carries exactly the shared policy."
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
