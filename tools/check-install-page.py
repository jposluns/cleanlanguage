#!/usr/bin/env python3
"""Check the install pages keep their family links, setup steps, and ids static, visible, and complete.

``site/install/index.html`` holds what applies to every AI system: the
downloads, the test, how to use it, spelling, and assurance. Each AI family
has its own setup page, ``site/install/<family>/index.html`` (Claude, ChatGPT,
Gemini, Copilot, and other AI systems), and ``/install/`` links each one with
a button near the top. All six are generated by ``tools/build-site.py`` on the
shared template (baseline). No script narrows or forwards anything: the pages
are plain static pages, so they read the same with JavaScript blocked, failed,
or switched off. This site no longer uses the template's install selector
(``select.js``, template specification, section 7.12); the old link forms
``/install/?ai=<family>`` and ``/install/#<family>`` land on ``/install/``,
where the family buttons sit at the top.

This is a TRIPWIRE for the common regressions in the STATIC MARKUP. It is
deliberately NOT a CSS engine or a browser.

What it verifies
----------------

1. On ``/install/``, each family has exactly 1 link, ``<a id=X href="/install/X/">``
   with the classes ``btn`` and ``inline``, none with ``aria-current``, none
   hidden by itself or an ancestor (``hidden``, ``inert``, ``aria-hidden="true"``
   in any case, or the class ``vh``, the template's visually-hidden class, or
   ``visually-hidden``, each matched as a whole class name); the 5 links sit
   in 1 paragraph, in the order Claude, ChatGPT, Gemini, Copilot, other AI
   systems, before the ``get`` id.
2. No element on any of the 6 pages carries the retired selector attributes
   ``data-picker``, ``data-family-link``, ``data-family-section``,
   ``data-picker-reset`` or ``data-picker-status``.
3. On ``/install/``, the ids ``pick``, ``get``, ``test``, ``how-to-use``,
   ``spelling``, ``assurance``, ``technical`` and the 5 family ids exist
   (existing deep links, such as ``/install/#pick`` and ``/install/#claude``),
   and on every page no id is duplicated.
4. Each family page exists (exit 3 if not) and has exactly 1 ``<h1>`` with
   visible text, at least 1 ``p.verified`` and at least 1 ``ol.steps``, none of
   them hidden by itself or an ancestor, and links to ``/install/#get`` and
   ``/install/#test``.
5. No inline code and no refused markup on any of the 6 pages, as checks 1 to
   10 of ``tools/check-inline-code.py`` define them for an HTML page, with that
   gate's own code: among them, no ``<script>`` without ``src`` other than a
   structured-data block, no ``on*`` attribute, no ``javascript:`` URL, no
   ``<style>`` element or ``style`` attribute, no script from another origin,
   and none of the elements that the parser reads differently from a browser.
6. Versioned asset tokens on each of the 6 pages: ``fonts.css``,
   ``palettes.css``, ``baseline.css`` and ``copy.js`` load from
   ``/assets/baseline/`` with ``?v=X.Y.Z``, the script with ``defer``; an
   optional ``site.css`` loads with ``?v=`` and 12 hexadecimal characters.
   Every ``<script>`` a page loads is 1 of the baseline scripts this site uses
   (``ALLOWED_SCRIPTS``: ``copy.js``, ``search.js``, ``rail.js``) from
   ``/assets/baseline/``, with the same token and ``defer``; ``select.js`` is
   refused.
7. ``site/_headers``, read with the parser of ``tools/check-headers.py``
   (header names compared without regard to case, comments ignored), has a
   ``/*`` rule that sets ``Content-Security-Policy`` exactly once, to exactly
   the shared policy, ``SHARED_CSP`` below (template specification, baseline
   1.4.1, section 9), and does not detach it. No rule sets or detaches
   ``X-Content-Security-Policy``, and no rule other than ``/*`` and ``/draft/*``
   sets, or other than ``/draft/*`` detaches, ``Content-Security-Policy``; a
   ``/draft/*`` rule appears only while a new
   version is staged, and ``tools/check-headers.py`` check 5 holds it to its
   exact lines. The policy allows ``'unsafe-inline'``, so a browser does not
   block inline code on these pages. The site's own pages must not use it
   (template specification, section 5), and check 5 and
   ``tools/check-inline-code.py`` enforce that rule.

What it does NOT verify (the reviewer's and cross-family QA's job)
-----------------------------------------------------------------

It does not apply any stylesheet or run any script. It does NOT detect a
stylesheet rule that hides a link or a step list, a closed ``<details>``
around them, a custom CLASS that hides, clips, zeroes opacity or positions
off-screen, a DESCENDANT wipe, or hiding by id. It does not check the wording
of the setup steps, only that they are present. Those are visible regressions
a browser check, a reviewer, or the tri-family QA catches. An exotic heading
character may still slip through the visible-text check. The inline-code
checks share the residual that ``tools/check-inline-code.py`` states.

Exit codes:
  0  the markup is static and complete, and the header discipline holds
  1  a family link, family page, id, retired attribute, asset token, or header discipline regressed
  3  a file could not be read, or a gate it reuses is missing
"""

from __future__ import annotations

import functools
import importlib.util
import re
import sys
from collections import Counter
from html.parser import HTMLParser
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
PAGE = REPO_ROOT / "site" / "install" / "index.html"
HEADERS = REPO_ROOT / "site" / "_headers"
WHERE = "site/install/index.html"

FAMILIES = ["claude", "chatgpt", "gemini", "copilot", "other-ai"]
FAMILY_PAGES = {fam: REPO_ROOT / "site" / "install" / fam / "index.html" for fam in FAMILIES}
TEMPLATE_IDS = ["pick", "get", "test", "how-to-use", "spelling", "assurance", "technical"]
RETIRED_ATTRS = ("data-picker", "data-family-link", "data-family-section", "data-picker-reset", "data-picker-status")
ALLOWED_SCRIPTS = ("copy.js", "search.js", "rail.js")
DRAFT_PATTERN = "/draft/*"
# The shared policy (template specification, baseline 1.4.1, section 9), on every page since promotion.
SHARED_CSP = (
    "default-src 'none'; script-src 'self' 'unsafe-inline' https://ajax.cloudflare.com "
    "https://static.cloudflareinsights.com; connect-src 'self' https://cloudflareinsights.com; "
    "style-src 'self'; font-src 'self'; img-src 'self'; base-uri 'none'; form-action 'none'; "
    "frame-ancestors 'none'"
)
BASELINE_ASSET = r'/assets/baseline/{name}\?v=[0-9]+\.[0-9]+\.[0-9]+"'
VOID = {"meta", "link", "img", "br", "hr", "input", "source", "wbr", "col"}
# Invisible characters a heading might be reduced to: zero-width spaces/joiner/BOM,
# no-break and soft-hyphen, word joiner, and the bidi marks.
ZERO_WIDTH = "​‌‍﻿ ⁠‎‏­"

INLINE_RULE = (
    "the site's own pages must not use inline code (template specification, section 5), and this gate "
    "and tools/check-inline-code.py enforce that rule"
)


def die(message: str) -> None:
    print(f"check-install-page: {message}", file=sys.stderr)
    raise SystemExit(3)


@functools.cache
def load_tool(name: str):
    """Load a sibling gate as a module, so this gate applies exactly its logic."""
    path = Path(__file__).resolve().parent / name
    if not path.is_file():
        die(f"tools/{name} does not exist")
    spec = importlib.util.spec_from_file_location(name.removesuffix(".py").replace("-", "_"), path)
    if spec is None or spec.loader is None:
        die(f"tools/{name} could not be loaded")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def inline_code(where: str, text: str) -> list[str]:
    """Check 5: each piece of inline code, read with tools/check-inline-code.py."""
    return [f"{where} {problem}; {INLINE_RULE}." for problem in load_tool("check-inline-code.py").inline_code_problems(text)]


# The template's visually-hidden class is .vh (site/assets/baseline/baseline.css). The common name
# visually-hidden is kept although no stylesheet here defines it: an author who adds it means to hide
# the element, and this gate cannot see whether a later stylesheet defines it, so it fails closed.
HIDING_CLASSES = ("vh", "visually-hidden")


def is_hiding_element(attrs: dict[str, str]) -> bool:
    classes = attrs.get("class", "").split()
    return (
        "hidden" in attrs
        or "inert" in attrs
        or attrs.get("aria-hidden", "").lower() == "true"
        or any(name in classes for name in HIDING_CLASSES)
    )


def has_visible_text(data: str) -> bool:
    return bool(data.translate({ord(c): None for c in ZERO_WIDTH}).strip())


class PageParser(HTMLParser):
    """Collects the static markup the install pages are checked against."""

    def __init__(self) -> None:
        super().__init__()
        self.stack: list[dict] = []
        self.order = 0
        self.id_counts: Counter = Counter()
        self.id_first: dict[str, int] = {}
        self.retired: list[str] = []
        self.anchors: list[dict] = []
        self.hrefs: list[str] = []
        self.h1: list[dict] = []
        self.verified: list[bool] = []
        self.steps: list[bool] = []
        self._h1: dict | None = None

    def handle_starttag(self, tag: str, attrs_list) -> None:
        attrs = {k.lower(): (v if v is not None else "") for k, v in attrs_list}
        self.order += 1
        classes = attrs.get("class", "").split()
        hiding = is_hiding_element(attrs) or any(frame["hiding"] for frame in self.stack)
        if "id" in attrs:
            self.id_counts[attrs["id"]] += 1
            self.id_first.setdefault(attrs["id"], self.order)
        for name in RETIRED_ATTRS:
            if name in attrs:
                self.retired.append(f"<{tag} {name}>")
        if tag == "a":
            parent = self.stack[-1] if self.stack else None
            self.hrefs.append(attrs.get("href", ""))
            self.anchors.append({
                "id": attrs.get("id"),
                "href": attrs.get("href", ""),
                "classes": classes,
                "current": "aria-current" in attrs,
                "hidden": hiding,
                "order": self.order,
                "parent": (parent["tag"], parent["order"]) if parent else None,
            })
        if tag == "h1":
            self._h1 = {"hidden": hiding, "text": False}
            self.h1.append(self._h1)
        if tag == "p" and "verified" in classes:
            self.verified.append(hiding)
        if tag == "ol" and "steps" in classes:
            self.steps.append(hiding)
        if tag not in VOID:
            self.stack.append({"tag": tag, "hiding": hiding, "order": self.order})

    def handle_endtag(self, tag: str) -> None:
        if tag == "h1":
            self._h1 = None
        for i in range(len(self.stack) - 1, -1, -1):
            if self.stack[i]["tag"] == tag:
                del self.stack[i:]
                break

    def handle_data(self, data: str) -> None:
        if self._h1 is not None and has_visible_text(data):
            self._h1["text"] = True


def parse(text: str) -> PageParser:
    parser = PageParser()
    parser.feed(text)
    parser.close()
    return parser


def common_checks(where: str, text: str, parser: PageParser) -> list[str]:
    """Checks 2, 3 (duplicates), 5 and 6, which hold on all 6 pages."""
    problems: list[str] = []
    for carrier in parser.retired:
        problems.append(f"{where}: the retired selector attribute appears on {carrier}; this site no longer uses select.js.")
    for dup_id, count in sorted(parser.id_counts.items()):
        if count > 1:
            problems.append(f'{where}: the id "{dup_id}" appears {count} times.')
    problems += inline_code(where, text)
    for name in ("fonts.css", "palettes.css", "baseline.css"):
        if not re.search(r'<link rel="stylesheet" href="' + BASELINE_ASSET.format(name=re.escape(name)), text):
            problems.append(f"{where}: {name} is not loaded from /assets/baseline/ with a ?v=X.Y.Z token.")
    if not re.search(r'<script src="' + BASELINE_ASSET.format(name=re.escape("copy.js")) + r" defer></script>", text):
        problems.append(f"{where}: copy.js is not loaded from /assets/baseline/ with a ?v=X.Y.Z token and defer.")
    for tag in re.findall(r"<script\b[^>]*\bsrc=[^>]*>", text):
        name = re.search(r'src="/assets/baseline/([a-z]+\.js)\?v=[0-9]+\.[0-9]+\.[0-9]+"', tag)
        if name is None or name.group(1) not in ALLOWED_SCRIPTS or not tag.endswith(" defer>"):
            problems.append(f"{where}: {tag} is not 1 of the baseline scripts this site uses ({', '.join(ALLOWED_SCRIPTS)}) with a ?v=X.Y.Z token and defer.")
    if "/assets/site.css" in text and not re.search(r'<link rel="stylesheet" href="/assets/site\.css\?v=[0-9a-f]{12}">', text):
        problems.append(f"{where}: site.css is not loaded with a ?v= content token.")
    return problems


def check_install_page(text: str) -> list[str]:
    """Checks 1 to 3, 5 and 6 on /install/."""
    parser = parse(text)
    where = WHERE
    problems = common_checks(where, text, parser)
    get_at = parser.id_first.get("get")
    found: list[dict] = []
    for fam in FAMILIES:
        mine = [anchor for anchor in parser.anchors if anchor["id"] == fam]
        if len(mine) != 1:
            problems.append(f"{where}: the {fam} family link appears {len(mine)} times; it must appear exactly once.")
            continue
        link = mine[0]
        found.append(link)
        if link["href"] != f"/install/{fam}/":
            problems.append(f'{where}: the {fam} family link points at {link["href"]!r}, not "/install/{fam}/".')
        if "btn" not in link["classes"] or "inline" not in link["classes"]:
            problems.append(f"{where}: the {fam} family link is not a button (the classes btn and inline).")
        if link["current"]:
            problems.append(f"{where}: the {fam} family link carries aria-current in the static markup.")
        if link["hidden"]:
            problems.append(f"{where}: the {fam} family link is hidden in the static markup.")
        if get_at is not None and link["order"] > get_at:
            problems.append(f'{where}: the {fam} family link comes after the "get" id; the family links sit at the top.')
    if len(found) == len(FAMILIES):
        parents = {link["parent"] for link in found}
        if len(parents) != 1 or next(iter(parents)) is None or next(iter(parents))[0] != "p":
            problems.append(f"{where}: the family links do not sit together in 1 paragraph.")
        if [link["order"] for link in found] != sorted(link["order"] for link in found):
            problems.append(f"{where}: the family links are not in the order {', '.join(FAMILIES)}.")
    for gid in TEMPLATE_IDS + FAMILIES:
        if parser.id_counts.get(gid, 0) == 0:
            problems.append(f'{where}: the id "{gid}" is missing; existing deep links use it.')
    return problems


def check_family_page(fam: str, text: str) -> list[str]:
    """Checks 2 to 6 on 1 family page."""
    parser = parse(text)
    where = f"site/install/{fam}/index.html"
    problems = common_checks(where, text, parser)
    if len(parser.h1) != 1:
        problems.append(f"{where}: {len(parser.h1)} <h1> elements; exactly 1 is required.")
    else:
        if not parser.h1[0]["text"]:
            problems.append(f"{where}: the <h1> has no visible text.")
        if parser.h1[0]["hidden"]:
            problems.append(f"{where}: the <h1> is hidden in the static markup.")
    if not parser.verified:
        problems.append(f'{where}: no <p class="verified"> line says when the steps were last verified.')
    elif any(parser.verified):
        problems.append(f"{where}: a verified line is hidden in the static markup.")
    if not parser.steps:
        problems.append(f'{where}: no <ol class="steps"> setup steps.')
    elif any(parser.steps):
        problems.append(f"{where}: a step list is hidden in the static markup.")
    for target in ("/install/#get", "/install/#test"):
        if target not in parser.hrefs:
            problems.append(f"{where}: no link to {target}.")
    return problems


def check_headers(headers: str) -> list[str]:
    """Check 7: the site-wide policy, read with the parser of tools/check-headers.py."""
    problems: list[str] = []
    entries = load_tool("check-headers.py").parse(headers)
    site_csp = [
        (number, kind, value) for number, pattern, kind, name, value in entries
        if pattern == "/*" and name.lower() == "content-security-policy"
    ]
    if len(site_csp) != 1 or site_csp[0][1] != "set":
        problems.append(
            f"the /* rule of site/_headers sets or detaches Content-Security-Policy {len(site_csp)} times "
            "(lines " + (", ".join(str(entry[0]) for entry in site_csp) or "none") + "); "
            "it must set it exactly once and detach it nowhere."
        )
    elif site_csp[0][2] != SHARED_CSP:
        problems.append(
            f"the site-wide Content-Security-Policy (site/_headers line {site_csp[0][0]}) is not exactly "
            f"the shared policy: {site_csp[0][2]!r}"
        )
    for number, pattern, kind, name, _ in entries:
        if name.lower() == "x-content-security-policy":
            problems.append(
                f"site/_headers line {number} names X-Content-Security-Policy under {pattern}; "
                "only Content-Security-Policy carries the policy."
            )
        elif name.lower() == "content-security-policy" and kind == "detach" and pattern not in ("/*", DRAFT_PATTERN):
            problems.append(
                f"site/_headers line {number} detaches Content-Security-Policy under {pattern}; only "
                f"{DRAFT_PATTERN} may detach it, because it sets the same policy again."
            )
        elif name.lower() == "content-security-policy" and kind == "set" and pattern not in ("/*", DRAFT_PATTERN):
            problems.append(
                f"site/_headers line {number} sets a Content-Security-Policy for {pattern}; only /* and "
                f"{DRAFT_PATTERN} may set one."
            )
    return problems


def main() -> int:
    for path in (PAGE, *FAMILY_PAGES.values(), HEADERS):
        if not path.is_file():
            die(f"{path.relative_to(REPO_ROOT)} does not exist")
    try:
        page_text = PAGE.read_text(encoding="utf-8")
        family_texts = {fam: path.read_text(encoding="utf-8") for fam, path in FAMILY_PAGES.items()}
        headers = HEADERS.read_text(encoding="utf-8")
    except (OSError, UnicodeError) as error:
        die(f"a file could not be read: {error}")

    problems = check_install_page(page_text)
    for fam in FAMILIES:
        problems += check_family_page(fam, family_texts[fam])
    problems += check_headers(headers)

    if problems:
        print("Install page problems found:")
        for problem in problems:
            print(f"  - {problem}")
        return 1

    print(
        "The install page links all five family pages with visible buttons at the top and keeps its ids; "
        "each family page carries its heading, verified line, and setup steps statically and visibly and "
        "links back to the downloads and the test; ids are unique, no retired selector markup remains, the "
        "six pages carry no inline code and load only the baseline's versioned assets, and the /* rule of "
        "site/_headers carries exactly the shared policy."
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
